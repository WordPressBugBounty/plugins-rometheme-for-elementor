<?php

namespace RTMKit\Modules\Helper;

if (!defined('ABSPATH')) exit;

/**
 * Builds wpml-config.xml from the widgets Elementor has actually registered.
 *
 * Reading the live control tree rather than parsing sources means the config
 * cannot drift as widgets gain or lose controls. Widgets are grouped by the
 * plugin that declares them, so the Pro add-on gets its own config file.
 */
class WpmlConfig
{
    /**
     * Elementor control type => WPML editor type.
     *
     * WPML understands only this handful. Anything else is not translatable
     * content and must stay out, or translators are handed noise.
     */
    const EDITOR_TYPES = [
        'text'     => 'LINE',
        'textarea' => 'AREA',
        'wysiwyg'  => 'VISUAL',
        'url'      => 'LINK',
        'media'    => 'MEDIA',
    ];

    /**
     * Control names that hold text but never translatable content.
     * Translating these breaks layout or targeting instead of localising it.
     */
    const DENYLIST = [
        'css_id',
        'css_classes',
        'element_id',
        'anchor_id',
        'target_id',
        'link_class',
        'button_css_id',
        'wrapper_class',
        'custom_class',
        'icon_class',
        'selector',
        'video_id',
        'shortcode',

        // Rendered as the HTML `name` attribute of a form input. Translating
        // it changes the POST key per language, so submissions and mail
        // notifications stop matching their fields.
        'name_input',

        // The value a checkbox/select option actually submits, not its label.
        'option_value',

        // Slider timing, passed straight into the carousel config.
        'slider_delay',
    ];

    /**
     * Sections that hold presentation rather than content.
     *
     * Elementor reports `tab` as "content" for every control on a registered
     * prototype -- including its own `_section_border` -- so the tab is not a
     * usable signal. The section name is.
     */
    const STYLE_SECTION_PATTERN = '/(style|effect|transform|animation|blur|custom_css|custom_attributes|responsive|masking|background|border|shadow|spacing|layout)/i';

    /**
     * Field names generated by Elementor group controls (background, in
     * particular). These are style knobs that merely happen to be typed as
     * text or media.
     */
    const GROUP_FIELD_PATTERN = '/(_image|_video_link|_video_fallback|_image_hover|_bg_image)$/';

    /**
     * Slugs of the plugins whose widgets should be catalogued.
     *
     * Derived from the plugin headers rather than widget name prefixes:
     * RomethemeForm names its widgets `text`, `email`, `select` and friends,
     * and RTMKit itself ships `site-logo` and `header-info`. A name prefix
     * silently loses all of those; the owning directory never does.
     *
     * @return string[]
     */
    public function family_slugs($author_match = 'rometheme')
    {
        if (!function_exists('get_plugins')) {
            require_once ABSPATH . 'wp-admin/includes/plugin.php';
        }

        $slugs = [];

        foreach (get_plugins() as $file => $data) {
            $author = isset($data['Author']) ? $data['Author'] : '';
            $name   = isset($data['Name']) ? $data['Name'] : '';

            if (stripos($author, $author_match) === false && stripos($name, $author_match) === false) {
                continue;
            }

            $slug = strtok($file, '/');
            if ($slug && $slug !== $file) {
                $slugs[] = $slug;
            }
        }

        return array_values(array_unique($slugs));
    }

    /**
     * Collect translatable fields for every registered widget belonging to one
     * of the given plugin slugs, keyed by owning plugin directory.
     *
     * @param string[] $slugs
     * @return array{plugins: array<string, array>, skipped: string[]}
     */
    public function collect(array $slugs)
    {
        $result = ['plugins' => [], 'skipped' => []];

        if (!class_exists('\Elementor\Plugin')) {
            return $result;
        }

        $widgets = \Elementor\Plugin::$instance->widgets_manager->get_widget_types();

        foreach ((array) $widgets as $name => $widget) {
            $plugin_dir = $this->owning_plugin_dir($widget);
            if ($plugin_dir === null) {
                continue;
            }

            if (!in_array(basename($plugin_dir), $slugs, true)) {
                continue;
            }

            $fields = $this->collect_fields($widget);
            if (empty($fields['fields']) && empty($fields['repeaters'])) {
                continue;
            }

            $result['plugins'][$plugin_dir][$name] = $fields;
        }

        foreach ($result['plugins'] as &$widgets_in_plugin) {
            ksort($widgets_in_plugin);
        }
        unset($widgets_in_plugin);

        ksort($result['plugins']);

        return $result;
    }

    /**
     * Count translatable fields, including repeater item fields.
     */
    public function count_fields(array $widget_fields)
    {
        $count = 0;
        foreach ($widget_fields as $data) {
            $count += count($data['fields']);
            foreach ($data['repeaters'] as $items) {
                $count += count($items);
            }
        }
        return $count;
    }

    /**
     * Resolve the plugin directory a widget class lives in.
     */
    private function owning_plugin_dir($widget)
    {
        try {
            $reflection = new \ReflectionClass($widget);
            $file = $reflection->getFileName();
        } catch (\ReflectionException $e) {
            return null;
        }

        if (!$file) {
            return null;
        }

        $file    = wp_normalize_path($file);
        $plugins = wp_normalize_path(WP_PLUGIN_DIR);

        if (strpos($file, $plugins . '/') !== 0) {
            return null;
        }

        $slug = strtok(substr($file, strlen($plugins) + 1), '/');

        return $slug ? $plugins . '/' . $slug : null;
    }

    /**
     * Split a widget's controls into top-level fields and repeater item fields.
     */
    private function collect_fields($widget)
    {
        $fields    = [];
        $repeaters = [];

        try {
            $controls = $widget->get_controls();
        } catch (\Exception $e) {
            return ['fields' => [], 'repeaters' => []];
        }

        foreach ((array) $controls as $control) {
            if (!is_array($control) || empty($control['name']) || empty($control['type'])) {
                continue;
            }

            $name = $control['name'];

            if ($control['type'] === 'repeater') {
                $items = [];
                $sub   = isset($control['fields']) ? (array) $control['fields'] : [];

                foreach ($sub as $field) {
                    if (!is_array($field) || empty($field['name']) || empty($field['type'])) {
                        continue;
                    }
                    // Repeater items are content by definition, so the section
                    // heuristic does not apply -- only the name filters do.
                    $editor = $this->editor_type($field['name'], $field['type'], null);
                    if ($editor !== null) {
                        $items[$field['name']] = $editor;
                    }
                }

                if (!empty($items)) {
                    ksort($items);
                    $repeaters[$name] = $items;
                }
                continue;
            }

            $editor = $this->editor_type(
                $name,
                $control['type'],
                isset($control['section']) ? $control['section'] : null
            );
            if ($editor !== null) {
                $fields[$name] = $editor;
            }
        }

        ksort($fields);
        ksort($repeaters);

        return ['fields' => $fields, 'repeaters' => $repeaters];
    }

    /**
     * Decide whether a control carries translatable content, and as what.
     * Returns null when it does not.
     */
    private function editor_type($name, $type, $section)
    {
        if (!isset(self::EDITOR_TYPES[$type])) {
            return null;
        }

        if (in_array($name, self::DENYLIST, true)) {
            return null;
        }

        // Underscore-prefixed *sections* belong to Elementor itself
        // (_section_background, _section_style); WPML already handles its core.
        //
        // Underscore-prefixed *names* are not a reliable signal: RTMKit
        // declares its own `_link` on Advanced Heading, which renders a real
        // anchor and does need translating. Section membership decides.
        if ($section !== null && $section[0] === '_') {
            return null;
        }

        // Responsive variants duplicate their desktop parent; including them
        // would ask a translator for the same string three times.
        if (preg_match('/_(tablet|mobile|laptop|widescreen|tablet_extra|mobile_extra)$/', $name)) {
            return null;
        }

        // Group-control artifacts: background images and video links are style,
        // not content, however they happen to be typed.
        if (preg_match(self::GROUP_FIELD_PATTERN, $name)) {
            return null;
        }

        if ($section !== null && preg_match(self::STYLE_SECTION_PATTERN, $section)) {
            return null;
        }

        return self::EDITOR_TYPES[$type];
    }

    /**
     * Render the XML document for one plugin's widgets.
     */
    public function build_xml(array $widget_fields)
    {
        $lines   = [];
        $lines[] = '<?xml version="1.0" encoding="UTF-8"?>';
        $lines[] = '<!-- Generated by `wp rtmkit i18n wpml-config`. Do not edit by hand. -->';
        $lines[] = '<wpml-config>';
        $lines[] = '  <elementor-widgets>';

        foreach ($widget_fields as $widget_name => $data) {
            $lines[] = '    <widget module="' . $this->attr($widget_name) . '">';

            if (!empty($data['fields'])) {
                $lines[] = '      <fields>';
                foreach ($data['fields'] as $field => $editor) {
                    $lines[] = '        <field editor_type="' . $this->attr($editor) . '">'
                        . $this->attr($field) . '</field>';
                }
                $lines[] = '      </fields>';
            }

            foreach ($data['repeaters'] as $repeater => $items) {
                $lines[] = '      <fields-in-item items_of="' . $this->attr($repeater) . '">';
                foreach ($items as $field => $editor) {
                    $lines[] = '        <field editor_type="' . $this->attr($editor) . '">'
                        . $this->attr($field) . '</field>';
                }
                $lines[] = '      </fields-in-item>';
            }

            $lines[] = '    </widget>';
        }

        $lines[] = '  </elementor-widgets>';
        $lines[] = '</wpml-config>';

        return implode("\n", $lines) . "\n";
    }

    private function attr($value)
    {
        return htmlspecialchars((string) $value, ENT_QUOTES | ENT_XML1, 'UTF-8');
    }
}
